// Pastry: pasteboard capture (text, links, images, files) and paste injection.
import AppKit
import Carbon.HIToolbox
import UniformTypeIdentifiers

struct Clip { var kind = "text", title = "", preview = "", meta = ""; var flavors: [(String, Data)] = [] }

enum Capture {
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    static let kb = { (n: Int) in ByteCountFormatter.string(fromByteCount: Int64(n), countStyle: .file) }

    static func clip(from pb: NSPasteboard) -> Clip? {
        var c = Clip()
        let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            // Finder copy: an image file shows the real picture (not the file icon); anything else shows its icon
            c.flavors = [(NSPasteboard.PasteboardType.fileURL.rawValue, Data(urls.map(\.absoluteString).joined(separator: "\n").utf8))]
            if urls.count == 1, isImage(urls[0]), let img = thumbnail(url: urls[0]) {
                c.kind = "image"; c.title = urls[0].lastPathComponent
                c.meta = "\(img.w) × \(img.h) · \(kb((try? urls[0].resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? img.png.count))"
                c.flavors.append((thumbUTI, img.png))
            } else {
                c.kind = "file"; c.title = urls.map(\.lastPathComponent).joined(separator: ", "); c.meta = urls.count == 1 ? "File" : "\(urls.count) files"
            }
            return c
        }
        // Screenshots / images from browsers, Preview etc. A plain-text flavor wins unless it is merely the image's URL.
        let textIsURL = URL(string: text)?.scheme?.hasPrefix("http") == true
        if text.isEmpty || textIsURL, let png = imagePNG(pb) {
            let sz = NSImage(data: png)?.size ?? .zero
            c.kind = "image"; c.title = "Image \(Int(sz.width))x\(Int(sz.height))"; c.meta = "\(Int(sz.width)) × \(Int(sz.height)) · \(kb(png.count))"
            c.flavors = [(NSPasteboard.PasteboardType.png.rawValue, png)]
            return c
        }
        guard let s = pb.string(forType: .string), !text.isEmpty else { return nil }
        c.title = String(text.prefix(300)).replacingOccurrences(of: "\n", with: " ")
        c.preview = String(text.prefix(1500)); c.meta = "\(s.count) character\(s.count == 1 ? "" : "s")"
        if textIsURL { c.kind = "link" }
        c.flavors = [(NSPasteboard.PasteboardType.string.rawValue, Data(s.utf8))]
        for t in [NSPasteboard.PasteboardType.rtf, .html] { if let d = pb.data(forType: t) { c.flavors.append((t.rawValue, d)) } }
        return c
    }
    static func isImage(_ url: URL) -> Bool {   // the resource-value type can be nil for temp / unreadable files, so fall back to the extension
        ((try? url.resourceValues(forKeys: [.contentTypeKey]).contentType) ?? UTType(filenameExtension: url.pathExtension))?.conforms(to: .image) == true }
    // PNG on the pasteboard, else any image flavor (TIFF, JPEG, PDF...) re-encoded as PNG
    static func imagePNG(_ pb: NSPasteboard) -> Data? {
        if let d = pb.data(forType: .png) { return d }
        guard pb.canReadObject(forClasses: [NSImage.self], options: nil), let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }
    static func thumbnail(url: URL, maxPixel: Int = 800) -> (png: Data, w: Int, h: Int)? {
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int,
              let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: maxPixel,
                                                                    kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary),
              let png = NSBitmapImageRep(cgImage: cg).representation(using: .png, properties: [:]) else { return nil }
        return (png, w, h)
    }
}

// changeCount polling
final class Monitor {
    let store: Store; var last = NSPasteboard.general.changeCount; var timer: Timer?
    var onChange: (() -> Void)?
    init(store: Store) { self.store = store }
    /// Cached system sound; falls back to the file in /System/Library/Sounds (NSSound(named:) can return nil), then the alert beep.
    static let sound: NSSound? = NSSound(named: "Pop") ?? NSSound(contentsOfFile: "/System/Library/Sounds/Pop.aiff", byReference: true)
    static func chime() {
        guard let s = sound else { NSSound.beep(); log("copy sound: Pop unavailable, beep"); return }
        if s.isPlaying { s.stop() }
        log("copy sound: play=\(s.play())")
    }
    func start() { timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() } }
    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != last else { return }
        last = pb.changeCount
        if Injector.selfWrite == pb.changeCount { return }
        guard Set((pb.types ?? []).map(\.rawValue)).isDisjoint(with: Capture.skipTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        // Source app: the pasteboard's own declaration (nspasteboard.org) beats the frontmost app, which can be Pastry or a launcher
        var app = (front?.bundleIdentifier ?? "", front?.localizedName ?? "Unknown")
        if let src = pb.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")), !src.isEmpty,
           let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: src) { app = (src, FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")) }
        if app.0 == Bundle.main.bundleIdentifier { app = ("", "Unknown") }   // resolved by content type when drawn
        if Prefs.ignoredApps.contains(app.0) { return }
        guard let c = Capture.clip(from: pb) else { return }
        store.upsert(kind: c.kind, title: c.title, preview: c.preview, meta: c.meta, app: app, flavors: c.flavors)
        log("captured \(c.kind): \(c.title.prefix(40))")
        if Prefs.playSound { Monitor.chime() }
        onChange?()
    }
}

// Restore the stored flavors to the pasteboard, then synthesize Cmd+V via CGEvent.
enum Injector {
    static var selfWrite = -1
    static func copy(flavors: [(String, Data)], plain: Bool = false) { write(flavors, plain: plain) }
    private static func write(_ flavors: [(String, Data)], plain: Bool) {
        let pb = NSPasteboard.general; pb.clearContents()
        let strOnly = flavors.filter { $0.0 == NSPasteboard.PasteboardType.string.rawValue }
        for (t, d) in (plain && !strOnly.isEmpty ? strOnly : flavors) where t != thumbUTI {
            if t == NSPasteboard.PasteboardType.fileURL.rawValue {
                pb.writeObjects(String(decoding: d, as: UTF8.self).split(separator: "\n").compactMap { URL(string: String($0)) as NSURL? })
            } else { pb.setData(d, forType: NSPasteboard.PasteboardType(t)) }
        }
        selfWrite = pb.changeCount
    }
    static func paste(flavors: [(String, Data)], into app: NSRunningApplication?, plain: Bool = false) { pasteMany([flavors], into: app, plain: plain) }
    /// Paste several items in order. All-text selections become one paste joined by newlines; anything else
    /// (images, files) is pasted one item at a time, rewriting the pasteboard before each ⌘V.
    static func pasteMany(_ items: [[(String, Data)]], into app: NSRunningApplication?, plain: Bool = false) {
        guard !items.isEmpty else { return }
        let str = NSPasteboard.PasteboardType.string.rawValue, rich: Set<String> = [NSPasteboard.PasteboardType.fileURL.rawValue, NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue]
        var queue = items
        if items.count > 1, items.allSatisfy({ f in f.contains { $0.0 == str } && !f.contains { rich.contains($0.0) } }) {
            let joined = items.compactMap { f in f.first { $0.0 == str }.map { String(decoding: $0.1, as: UTF8.self) } }.joined(separator: "\n")
            queue = [[(str, Data(joined.utf8))]]
        }
        app?.activate()
        guard AXIsProcessTrusted() else { // needs Accessibility to post events; last clip is at least on the pasteboard
            write(queue[queue.count - 1], plain: plain); log("Accessibility permission missing; item copied but Cmd+V not sent"); return
        }
        func step(_ i: Int) {
            guard i < queue.count else { return }
            write(queue[i], plain: plain)
            DispatchQueue.main.asyncAfter(deadline: .now() + (i == 0 ? 0.15 : 0.05)) {
                let src = CGEventSource(stateID: .combinedSessionState)
                for down in [true, false] {
                    let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                    e?.flags = .maskCommand; e?.post(tap: .cghidEventTap)
                }
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) { step(i + 1) }   // let the target read the pasteboard before it changes
            }
        }
        step(0)
    }
}
